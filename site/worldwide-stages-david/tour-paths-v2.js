export function makeTourTransit(fromPose,chapter,previousExit='route') {
 if(chapter.entry==='dissolve'||previousExit==='dissolve')return [{mode:'dissolve',...chapter.poses[0],seconds:1.2}];
 if(chapter.entry==='route'){
  const first=chapter.approach[0];
  if(JSON.stringify(first.p)!==JSON.stringify(fromPose.p)||JSON.stringify(first.t)!==JSON.stringify(fromPose.t))throw new Error('Tour route starting pose differs');
  return chapter.approach.slice(1).map(p=>({mode:'flight',...p}));
 }
 const d=chapter.poses[0],alt=Math.max(80,fromPose.p[1],d.p[1]);
 return [{mode:'flight',p:[fromPose.p[0],alt,fromPose.p[2]],t:fromPose.t,seconds:3},{mode:'flight',p:[d.p[0],alt,d.p[2]],t:d.t,seconds:5},{mode:'flight',...d,seconds:3}];
}
